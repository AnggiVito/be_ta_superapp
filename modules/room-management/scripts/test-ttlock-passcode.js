import { ttlockService } from '../services/ttlock/ttlockService.js';
import { logger } from '../core/utils/logger.js';

/**
 * Test script untuk menguji TTLock API passcode generation
 * 
 * CATATAN: Script ini membutuhkan Lock ID yang valid
 * Dapatkan Lock ID dari TTLock app atau API
 */

async function testPasscodeGeneration() {
  console.log('🔐 Testing TTLock Passcode Generation\n');
  console.log('============================================================\n');

  try {
    // Get access token first
    console.log('📌 Step 1: Authenticating with TTLock...');
    const token = await ttlockService.getValidToken();
    
    if (!token) {
      console.error('❌ Failed to get access token!');
      return;
    }
    
    console.log('✅ Authentication successful!');
    console.log(`   Token: ${token.substring(0, 20)}...\n`);

    // Your actual Lock ID from TTLock account
    const lockId = '12405430'; // Lock: "nyobaajam"
    
    console.log('📌 Step 2: Testing Passcode Creation...');
    console.log(`   Lock ID: ${lockId}`);
    console.log(`   Lock Name: nyobaajam\n`);

    // Test 1: Create Permanent Passcode
    console.log('🔐 Test 1: Creating Permanent Passcode...');
    try {
      const permanentResult = await ttlockService.createPermanentPasscode(
        lockId,
        'Test Permanent - Room 101'
        // passcode auto-generated by TTLock
      );

      console.log('✅ Permanent passcode created!');
      console.log(`   Response: ${JSON.stringify(permanentResult, null, 2)}\n`);
    } catch (error) {
      console.error('❌ Failed to create permanent passcode:');
      console.error(`   ${error.message}\n`);
    }

    // Test 2: Create Temporary Passcode
    console.log('🔐 Test 2: Creating Temporary Passcode...');
    try {
      const now = Date.now();
      const startDate = now;
      const endDate = now + (7 * 24 * 60 * 60 * 1000); // Valid for 7 days

      const temporaryResult = await ttlockService.createTemporaryPasscode(
        lockId,
        'Test Temporary - Guest Access',
        startDate,
        endDate
        // passcode auto-generated by TTLock
      );

      console.log('✅ Temporary passcode created!');
      console.log(`   Valid from: ${new Date(startDate).toLocaleString()}`);
      console.log(`   Valid until: ${new Date(endDate).toLocaleString()}`);
      console.log(`   Response: ${JSON.stringify(temporaryResult, null, 2)}\n`);
    } catch (error) {
      console.error('❌ Failed to create temporary passcode:');
      console.error(`   ${error.message}\n`);
    }

    // Test 3: Get Passcode List
    console.log('🔐 Test 3: Getting Passcode List...');
    try {
      const passcodeList = await ttlockService.getPasscodeList(lockId, 1, 20);

      console.log('✅ Passcode list retrieved!');
      console.log(`   Total passcodes: ${passcodeList.total || 0}`);
      
      if (passcodeList.list && passcodeList.list.length > 0) {
        console.log('\n   📋 Recent passcodes:');
        passcodeList.list.slice(0, 5).forEach((pwd, index) => {
          console.log(`   ${index + 1}. ID: ${pwd.keyboardPwdId}, Name: ${pwd.keyboardPwdName}`);
        });
      }
      console.log('');
    } catch (error) {
      console.error('❌ Failed to get passcode list:');
      console.error(`   ${error.message}\n`);
    }

    console.log('============================================================');
    console.log('\n✅ TTLock Passcode API Testing Complete!');
    console.log('   All passcode operations are working correctly.\n');
    console.log('💡 Next Steps:');
    console.log('   1. Add Lock ID (12405430) to your rooms in database');
    console.log('   2. Use room-management API endpoints to create passcodes');
    console.log('   3. Passcodes will be automatically synced with TTLock\n');

  } catch (error) {
    console.error('\n❌ Error testing TTLock API:');
    console.error(`   ${error.message}`);
    
    if (error.response?.data) {
      console.error('\n   API Response:');
      console.error(`   ${JSON.stringify(error.response.data, null, 2)}`);
    }
  }
}

// Run the test
testPasscodeGeneration()
  .then(() => {
    console.log('Test completed.');
    process.exit(0);
  })
  .catch((error) => {
    console.error('Test failed:', error);
    process.exit(1);
  });
